def durable_sync(files, dst_dir):
    """Mirror files into dst_dir (e.g. an HDFS mount) so a checkpoint survives the loss of
    the worker's ephemeral local disk. Writes to a sibling .tmp then os.replace, so a crash
    mid-copy can't leave a truncated checkpoint. Best-effort: never raises into training."""
    if not dst_dir:
        return
    try:
        dst = Path(dst_dir)
        dst.mkdir(parents=True, exist_ok=True)
        for f in files:
            f = Path(f)
            if not f.exists():
                continue
            tmp = dst / (f.name + ".tmp")
            shutil.copyfile(f, tmp)
            os.replace(tmp, dst / f.name)
    except Exception as e:
        print(f"[lewam-uni] WARN durable ckpt sync -> {dst_dir} failed: {e}", flush=True)


def subgoal_lambda(source: str, schedule: str, progress: float, lam_max: float, center: float, sharpness: float) -> float:
    """
    Probability that a training subgoal is generated by the planner of level 1 instead of the hindsight subgoal

    Args:
        source (str): "hindsight" (0), "generated" (1) or "scheduled"
        schedule (str): source=scheduled: "constant" (lam_max), "linear" (lam_max * progress) or "sigmoid"
            (sigmoid of the progress, renormalized to go from 0 to lam_max)
        progress (float): training progress in [0, 1]
        lam_max (float): the final value
        center (float): sigmoid: progress of the transition
        sharpness (float): sigmoid: slope of the transition

    Returns:
        lam (float): the probability
    """
    assert source in ("hindsight", "generated", "scheduled"), source
    assert schedule in ("constant", "linear", "sigmoid"), schedule
    if source != "scheduled":
        return float(source == "generated")
    if schedule == "constant":
        return lam_max
    if schedule == "linear":
        return lam_max * progress
    sigmoid = lambda x: 1 / (1 + math.exp(-sharpness * (x - center)))
    return lam_max * (sigmoid(progress) - sigmoid(0)) / (sigmoid(1) - sigmoid(0))
